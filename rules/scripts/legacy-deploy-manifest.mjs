#!/usr/bin/env node
// Offline review tool only. Never imported by a gateway or signer.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';

export const CUTOFF = '973675'; // Reviewed historical boundary, strictly before.
const inscription = value => typeof value === 'string' && /^[0-9a-f]{64}i(?:0|[1-9][0-9]*)$/.test(value);
const need = (value, code) => { if (!value) throw Error(code); };
export function manifestFromDeployments(rows) {
  need(Array.isArray(rows), 'manifest_deployments');
  const elements = {}, seen = new Set();
  for (const row of rows) {
    need(row && typeof row.dmt === 'boolean' && Number.isSafeInteger(row.blck) && row.blck >= 0, 'manifest_deployment');
    if (!row.dmt || BigInt(row.blck) >= BigInt(CUTOFF)) continue;
    need(inscription(row.ins) && inscription(row.elem) && (row.prv == null || inscription(row.prv)) && !seen.has(row.ins), 'manifest_identity');
    seen.add(row.ins);
    (elements[row.elem] ??= []).push({ id: row.ins, privilege: row.prv ?? null });
  }
  return { network: 'mainnet', cutoff: CUTOFF, elements: Object.fromEntries(Object.keys(elements).sort().map(id =>
    [id, elements[id].sort((a, b) => a.id < b.id ? -1 : 1)])) };
}
export function manifestSource(manifest) {
  return "import { freezeDocument } from './settings-v2.js';\n\n// Generated by rules/scripts/legacy-deploy-manifest.mjs. Membership is frozen;\n// holder addresses are deliberately absent. Exclude the configured authority at lookup.\nexport const LEGACY_DEPLOY_MANIFEST = freezeDocument(" + JSON.stringify(manifest, null, 2) + ');\n';
}
// No lengths/totals endpoint, no concurrency, no writes, no redirects. The
// indexer's list is append-only; the pre-cutoff subset is already final.
export async function scanDeployments(base, { fetcher = fetch, pace = () => new Promise(r => setTimeout(r, 1100)) } = {}) {
  const url = new URL(base); need(url.protocol === 'https:' && !url.username && !url.password && !url.search && !url.hash, 'manifest_url');
  const rows = [];
  for (let offset = 0; ; offset += 500) {
    if (offset) await pace();
    const response = await fetcher(new URL(`/r/tap/getDeployments?offset=${offset}&max=500`, url), { method: 'GET', redirect: 'error' });
    need(response.ok, 'manifest_http');
    const page = (await response.json()).result;
    need(Array.isArray(page) && page.length <= 500, 'manifest_page'); rows.push(...page);
    if (page.length < 500) return rows;
  }
}
export async function main(args) {
  const options = {};
  for (let i = 0; i < args.length; i += 2) {
    need(['--input', '--indexer', '--output', '--compare'].includes(args[i]) && args[i + 1] && !Object.hasOwn(options, args[i]), 'manifest_usage');
    options[args[i]] = args[i + 1];
  }
  need(!!options['--input'] !== !!options['--indexer'] && options['--output'], 'manifest_usage');
  const rows = options['--input'] ? JSON.parse(await readFile(options['--input'], 'utf8')) : await scanDeployments(options['--indexer']);
  const manifest = manifestFromDeployments(rows), source = manifestSource(manifest);
  if (options['--compare']) need(source === manifestSource(manifestFromDeployments(JSON.parse(await readFile(options['--compare'], 'utf8')))), 'manifest_scan_mismatch');
  await writeFile(options['--output'], source);
  process.stdout.write(JSON.stringify({ cutoff: manifest.cutoff, elements: Object.keys(manifest.elements).length,
    deployments: Object.values(manifest.elements).reduce((n, a) => n + a.length, 0), sha256: createHash('sha256').update(source).digest('hex') }) + '\n');
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main(process.argv.slice(2));
