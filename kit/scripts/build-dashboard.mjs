import { copyFile, mkdir } from 'node:fs/promises';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

// Package the same browser wallet and existing console styles with the kit.
// There is no runtime dependency on a separately served website checkout.
const target = new URL('../dashboard/', import.meta.url);
await mkdir(new URL('fonts/', target), { recursive: true });
await build({ entryPoints: [fileURLToPath(new URL('../lib/tap-wallet-mint.mjs', import.meta.url))],
  outfile: fileURLToPath(new URL('wallet.js', target)), bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'eof', banner: { js: '// Generated by kit/scripts/build-player-wallet.mjs. Edit kit/lib/tap-wallet-mint.mjs and inscription-core.mjs.' } });
for (const file of ['console.css', ...['fraunces-latin-wght-normal', 'atkinson-hyperlegible-next-latin-wght-normal', 'ibm-plex-mono-latin-400-normal', 'ibm-plex-mono-latin-500-normal'].map(name => 'fonts/' + name + '.woff2')])
  await copyFile(new URL('../../playground/console/' + file, import.meta.url), new URL(file, target));
