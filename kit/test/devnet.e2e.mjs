import { temp, cleanup } from './helpers.mjs';

test('local Trac/MSB, gateway and kit: own-account TNK, transfer, craft and mint', { timeout: 120000 }, async t => {
  await diskSpace(); const dir = await temp(t);
  await writeFile(join(dir, 'process.json'), JSON.stringify({ pid: process.pid, purpose: 'local-kit-devnet' }));
  const local = await localNetwork({ directory: join(dir, 'peers') }); cleanup(t, () => local.close());
  const validator = await local.msb(), bus = await local.client(validator);
  const indexer = await local.peer('indexer', bus), writer = await local.peer('writer', bus, indexer.base.key.toString('hex'));
  for (const p of [indexer, writer]) await local.fund(validator, p.wallet);
  const admin = controls(indexer, bus), relay = controls(writer, bus);
  await admin.setup({ writer: writer.writerLocalKey }); await until(() => writer.base.writable, 'writer admission');
  const walletDir = join(dir, 'wallet'), password = 'disposable devnet password';
  await init({ directory: walletDir, password }); const wallet = await unlock({ directory: walletDir, password }); cleanup(t, () => wipeWallet(wallet));
  await local.fund(validator, wallet);
  const owner = publicKey(wallet), trac = runtimeTrac(writer, { network: deployment.network, localOnly: true, msb: bus });
  const raw = [mine('0'.repeat(64), 1000), ...chain(30, checkpoint)], hashAt = h => raw[h] ? parseHeader(raw[h]).hash : null;
  await relay.post({ op: 'hd', value: { headers: raw.slice(1, 7) } }); await until(async () => (await trac.head()).counted === 1, 'counted block');
  await relay.post({ op: 'bt', value: signedBatch({ n: 1, from: 1, to: 1, ops: ['p0', 'p1'].map(asset => ({ op: 'mk', to: owner, asset, amount: '100' })) }) });
  await until(async () => await trac.balance(owner, 'p0') === '100', 'funded matter');
  const store = await Store.open(join(dir, 'gateway')); cleanup(t, () => store.close());
  const intake = new Intake({ store, network: deployment.network, secret: Buffer.alloc(32, 9), hashAt, puzzleBits: 0 });
  await intake.observe({ tip: 6, hash: hashAt(6), counted: 1, confirmed: 1 });
  const mints = new Mints({ store, network: deployment.network, operations: { supportsMintBatches: true }, committee: {}, payments: {}, inscriber: { quote: async () => '100' }, reads: {
    ...feeFixture({ store, network: deployment.network, baseFee: '10' }), counted: async () => (await trac.head()).counted, balance: (...args) => trac.balance(...args),
    assetContext: async () => ({ deployment: { active: true, kind: 'compound' }, tier: 1, treasury: 'local-treasury', firstMakerAddress: 'local-first-maker' })
  } });
  const http = await serve({ intake, files: new Files(join(dir, 'static')), mints }); cleanup(t, () => http.close());
  const journal = await Journal.open(walletDir, `${deployment.network}/${owner}`, { intervalMs: 0 }); cleanup(t, () => journal.close());
  const agent = new Agent({ bitcoinNetwork: 'regtest', wallet, network: deployment.network, trac, service: new ServiceClient({ origin: http.url, network: deployment.network, gateway: intake.gateway }), journal, dryRun: false, puzzleBits: 0, powLimitBits: 0x207fffff });
  const feeBefore = bufferToBigInt((await bus.state.getNodeEntry(wallet.address)).balance);
  const send = async args => { const result = await agent.transaction(args); await until(async () => (await trac.transactionStatus(result.tx)).state === 'accepted', args.op + ' acceptance'); return result; };
  await send({ actionId: 'transfer', op: 'tf', value: { to: encodeTracAddress(indexer.wallet.publicKey), assets: [['p0', '10']] } });
  assert.equal(await trac.balance(owner, 'p0'), '90');
  await relay.post({ op: 'hd', value: { headers: raw.slice(7, 13) } }); await until(async () => (await trac.head()).counted === 7, 'craft clock');
  const feeAfter = bufferToBigInt((await until(async () => { const r = await bus.state.getNodeEntry(wallet.address); return bufferToBigInt(r.balance) < feeBefore ? r : null; }, 'own account fee')).balance);
  assert.ok(feeAfter < feeBefore);
  await intake.observe({ tip: 12, hash: hashAt(12), counted: 7, confirmed: 7 });
  const patterns = [0, 1].map(number => ({ number, name: 'dmwlocal' + number, fld: 4, dt: 'n', pat: '[0-9]', historyHeight: 6, rarity: 7 }));
  const craft = await agent.craft({ actionId: 'fusion', inputs: [['p0', '2'], ['p1', '3']], patterns }); assert.equal(craft.state, 'received');
  const payload = journal.get('craft/fusion').body.p;
  await relay.post({ op: 'bt', value: signedBatch({ n: 2, from: 2, to: 8, hx: [raw[13]], ops: [{ op: 'xc', request: payload.request, sig: payload.sig }] }) });
  await until(async () => await trac.balance(owner, craft.compound.id) === '1', 'owner exchange');
  const mint = await agent.makeReal({ actionId: 'compound-mint', asset: craft.compound.id, amount: '1', receiver: bitcoinAddress(), payer: bitcoinAddress('regtest', 2), compound: true });
  const row = store.get('mints', mint.request.id); assert.equal(Object.hasOwn(row.request, 'block'), false);
  await relay.post({ op: 'bt', value: signedBatch({ n: 3, from: 9, to: 9, hx: [raw[14]], ops: [row.op] }) });
  await until(async () => (await trac.mint(row.id))?.s === 0, 'owner mint escrow'); assert.equal(await trac.balance(owner, craft.compound.id), '0');
  await relay.post({ op: 'bt', value: signedBatch({ n: 4, from: 10, to: 10, hx: [raw[15]], ops: [{ op: 'rl', id: row.id, inscription: 'ab'.repeat(32) + 'i0' }] }) });
  await until(async () => (await trac.mint(row.id))?.s === 1, 'mint completion');
  t.diagnostic(JSON.stringify({ network: deployment.network, counted: 10, paths: ['tf', 'xc', 'rq', 'rl'], tnkSpent: (feeBefore - feeAfter).toString(), pid: process.pid }));
});
